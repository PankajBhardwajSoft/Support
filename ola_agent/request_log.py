"""Structured request logging (Part 3, Task 12): one JSON-Lines entry per request.

Every text value is passed through the same phone masking the model input
uses, right before it is written, so a raw phone number never reaches disk
(rule.md 2.9) even if one slips into an answer.
"""

from __future__ import annotations

import json
import os
import threading
import uuid
from datetime import datetime, timezone
from typing import Any

from ola_agent.guardrails import mask_phones
from ola_agent.rag.embeddings import ROOT

LOG_PATH = os.path.join(ROOT, "logs", "requests.jsonl")

# Every entry has these keys, so log lines are easy to read and query.
FIELDS = ("ts", "trace_id", "endpoint", "session_id", "question", "answer",
          "guardrails_fired", "sources", "grounded", "status", "duration_ms")

# Generated by us, never user text. Not masked: a random hex ID can contain a
# 10-digit run that looks like a phone number, and masking it would break tracing.
_UNMASKED = ("ts", "trace_id", "session_id")

_lock = threading.Lock()


def new_trace_id() -> str:
    return uuid.uuid4().hex


def _mask(value: Any) -> Any:
    if isinstance(value, str):
        return mask_phones(value)[0]
    if isinstance(value, dict):
        return {k: _mask(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_mask(v) for v in value]
    return value


def write_entry(**fields: Any) -> dict:
    """Append one masked entry to LOG_PATH and return it."""
    entry = {key: None for key in FIELDS}
    entry["ts"] = datetime.now(timezone.utc).isoformat(timespec="milliseconds")
    entry.update(fields)
    entry = {k: v if k in _UNMASKED else _mask(v) for k, v in entry.items()}
    # ensure_ascii escapes newlines and Unicode line separators, so one entry is always one line.
    line = json.dumps(entry, ensure_ascii=True)
    path = LOG_PATH
    with _lock:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    return entry


def read_entries(path: str | None = None) -> list[dict]:
    path = path or LOG_PATH
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]
